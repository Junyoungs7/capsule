const utc = (k: string) => Date.UTC(+k.slice(0, 4), +k.slice(5, 7) - 1, +k.slice(8, 10))

/** 음력 [월, 일], 표 범위 밖이면 null */
export function lunarOf(d: Date): [number, number] | null {
  const t = Date.UTC(d.getFullYear(), d.getMonth(), d.getDate())
  for (let i = LUNAR.length - 2; i >= 0; i--) {
    const s = utc(LUNAR[i][0])
    if (t >= s) return t < utc(LUNAR[i + 1][0]) ? [LUNAR[i][1], (t - s) / 86_400_000 + 1] : null
  }
  return null
}
