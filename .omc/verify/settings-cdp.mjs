// (a6) Settings window suite — HEADLESS only (headless.mjs). The separate 940×680 settings window: 8 sections in a left nav,
// search dims the rest and jumps, every live row writes the real store key / calls the real Rust command, 준비 중 rows are inert,
// 연결 tabs (기기 · 함께 쓰기 · 화면 배치 · 키보드 · 고급) all visible, pairing digits, Deskflow import = one read-only call,
// hub 설정 / '설정에서 자세히' open it, Esc closes it.   node .omc/verify/settings-cdp.mjs
import { start, sleep, suite } from './headless.mjs'

const { ok, until, done } = suite('settings')
const h = await start()
const GEO = { x: 490, y: 176, w: 940, h: 680 }
try {
  h.handlers.autostart = (p, a) => (a.on === undefined || a.on === null ? false : a.on)
  h.handlers.link_import = () => ({ me: 'DESK', peer: 'MacBook Pro', side: 'right', port: 24800, tls: true, doubleTap: false, filePort: 24810, keymap: 'habit', keyRows: [], ime: 'hera', autoSaverMin: 0, locator: true })
  const sw = await h.open('settings&sec=general', { label: 'settings', geo: GEO })
  await until(() => sw.eval(`!!document.querySelector('.swin .nav')`), 8000)
  await sleep(400)
  const sec = () => sw.eval(`document.querySelector('.swin .pin').dataset.pane`)
  const nav = await sw.eval(`[...document.querySelectorAll('.swin .nav [data-sec]')].map((b) => b.textContent.trim())`)
  ok('8 sections in the left nav: 일반 · Island · 펫 · 연결 · 채팅 · 터미널·아라 · 단축키 · 정보', nav.join('|') === '일반|Island|펫|연결|채팅|터미널 · 아라|단축키|정보', nav.join('|'))
  ok('window fills 940×680 (title bar 44 · nav 216)', await until(() => sw.eval(`(() => { const b = document.querySelector('.swin .sbox').getBoundingClientRect(), n = document.querySelector('.swin .nav').getBoundingClientRect(); return Math.round(b.width) === 940 && Math.round(b.height) === 680 && Math.round(n.width) === 216 })()`)))
  ok('own title-bar drag (no OS caption region)', await sw.eval(`!document.querySelector('[data-tauri-drag-region]')`))

  /* 검색 */
  await sw.clickSel('.swin .wsearch input')
  await sw.type('페어링')
  ok('search "페어링" → other sections dim, jumps to 연결', await until(async () => (await sec()) === 'link' && (await sw.eval(`[...document.querySelectorAll('.swin .nav [data-sec]')].filter((b) => !b.classList.contains('dim')).map((b) => b.dataset.sec).join()`)) === 'link'))
  await sw.eval(`(() => { const i = document.querySelector('.swin .wsearch input'); Object.getOwnPropertyDescriptor(HTMLInputElement.prototype, 'value').set.call(i, ''); i.dispatchEvent(new Event('input', { bubbles: true })) })()`)
  ok('clearing the search undims everything', await until(() => sw.eval(`!document.querySelector('.swin .nav .dim')`)))

  /* 일반 */
  await sw.clickSel('.swin .nav [data-sec=general]')
  await until(async () => (await sec()) === 'general')
  const row = (t) => `[...document.querySelectorAll('.swin .srow')].find((r) => r.querySelector('.tt b')?.textContent.startsWith(${JSON.stringify(t)}))`
  const press = (t, sel = '.sw') => sw.eval(`${row(t)}.querySelector('${sel}').click()`)
  let n = h.calls.length
  await press('Windows 시작 시')
  ok('autostart switch → Rust autostart(on: true) (default off)', await until(() => h.calls.slice(n).some((c) => c[1] === 'autostart' && c[2].on === true)))
  await press('상단 공간 확보')
  ok('상단 공간 확보 → appbar.on', await until(() => h.store.get('appbar.on') === true))
  ok('할 일 · 날짜 없이 저장한 할 일 알림 = on by default', await sw.eval(`${row('날짜 없이 저장한')}.querySelector('.sw').getAttribute('aria-pressed') === 'true'`))
  await press('날짜 없이 저장한')
  ok('…off → todo.quickAlarm = false', await until(() => h.store.get('todo.quickAlarm') === false))
  await press('날씨·시간 효과')
  ok('날씨·시간 효과 → fx.enabled = false', await until(() => h.store.get('fx.enabled') === false))
  ok('트레이 아이콘 = 준비 중 (inert)', await sw.eval(`${row('트레이 아이콘')}.dataset.soon === 'true' && getComputedStyle(${row('트레이 아이콘')}).pointerEvents === 'none' && /준비 중/.test(${row('트레이 아이콘')}.textContent)`))
  const step = (d) => sw.eval(`${row('화면보호기')}.querySelector('.step button[aria-label=${d > 0 ? '늘리기' : '줄이기'}]').click()`)
  await step(1)
  ok('stepper + → ascii.idleMin 11 (number rolls)', await until(() => h.store.get('ascii.idleMin') === 11 && sw.eval(`${row('화면보호기')}.querySelector('.step b').textContent === '11분'`)))
  for (let i = 0; i < 12; i++) await step(-1)
  ok('stepper stops at 0 = 끔', await until(() => h.store.get('ascii.idleMin') === 0 && sw.eval(`${row('화면보호기')}.querySelector('.step b').textContent === '끔'`)))
  await sw.eval(`(() => { const i = ${row('도시')}.querySelector('input'); i.focus(); Object.getOwnPropertyDescriptor(HTMLInputElement.prototype, 'value').set.call(i, '부산'); i.dispatchEvent(new Event('input', { bubbles: true })); i.blur() })()`)
  ok('도시 → fx.city', await until(() => h.store.get('fx.city') === '부산'))

  /* Island */
  await sw.clickSel('.swin .nav [data-sec=island]')
  await until(async () => (await sec()) === 'island')
  await sw.clickSel('.swin [data-place-set=bl]')
  ok('위치 왼쪽 아래 → island.place = bl (preview moves)', await until(() => h.store.get('island.place') === 'bl' && sw.eval(`document.querySelector('.swin .ipv .mcap').dataset.place === 'bl'`)))
  await sw.clickSel('.swin [data-size-set=xl]')
  ok('크기 아주 크게 → island.size = xl', await until(() => h.store.get('island.size') === 'xl'))
  await press('전체화면 앱에서')
  ok('전체화면 숨기기 → island.autohide = false', await until(() => h.store.get('island.autohide') === false))
  await sw.clickSel('.swin [data-place-set=br]')
  await sw.clickSel('.swin [data-size-set=m]')

  /* 연결 */
  await sw.clickSel('.swin .nav [data-sec=link]')
  await until(async () => (await sec()) === 'link')
  const tabs = await sw.eval(`[...document.querySelectorAll('.swin .tabs2 [data-ltab]')].map((b) => b.textContent)`)
  ok('연결 tabs: 기기 · 함께 쓰기 · 화면 배치 · 키보드 · 고급 (배치·키보드 not under 고급)', tabs.join('|') === '기기|함께 쓰기|화면 배치|키보드|고급', tabs.join('|'))
  n = h.calls.length
  await sw.eval(`document.querySelector('.swin .hero .sw').click()`)
  ok('hero switch → link.enabled + link_apply (Hera Link, not Deskflow)', (await until(() => h.store.get('link.enabled') === true)) && (await until(() => h.calls.slice(n).some((c) => c[1] === 'link_apply'), 3000)))
  await sw.clickSel('.swin [data-ltab=share]')
  await until(() => sw.eval(`document.querySelectorAll('.swin .sh').length === 6`))
  ok('함께 쓰기: 6 switches incl. "채팅 알림은 커서가 있는 PC 에서만"', await sw.eval(`/커서가 있는 PC 에서만/.test(document.querySelector('.swin .sh[data-share=chat]').textContent)`))
  await sw.eval(`document.querySelector('.swin .sh[data-share=clip] .sw').click()`)
  ok('클립보드 off → link.share.clip = false (Rust link::shared reads it)', await until(() => h.store.get('link.share')?.clip === false))
  await sw.clickSel('.swin [data-ltab=layout]')
  ok('화면 배치: monitor canvas + 두 번 치기 · 커서 찾기 · 자동 화면보호기', await until(() => sw.eval(`!!document.querySelector('.swin .mon-canvas') && /두 번 치기/.test(document.querySelector('.swin .pin').textContent) && /커서 찾기/.test(document.querySelector('.swin .pin').textContent)`)))
  await press('가장자리 두 번 치기')
  ok('두 번 치기 → link.cfg.doubleTap', await until(() => h.store.get('link.cfg')?.doubleTap === true))
  await sw.clickSel('.swin [data-ltab=keyboard]')
  await sw.clickSel('.swin [data-keymap=position]')
  ok('키보드 preset → link.cfg.keymap = position', await until(() => h.store.get('link.cfg')?.keymap === 'position'))
  await sw.clickSel('.swin [data-keymap=custom]')
  ok('직접 정하기 shows the key rows editor', await until(() => sw.eval(`/줄 추가/.test(document.querySelector('.swin .pin').textContent)`)))
  await sw.clickSel('.swin [data-ltab=adv]')
  await press('연결 암호화')
  ok('연결 암호화 off → link.cfg.tls = false', await until(() => h.store.get('link.cfg')?.tls === false))
  n = h.calls.length
  await sw.clickSel('.swin [data-import]')
  ok('Deskflow 설정 가져오기 = one read-only link_import call (nothing else Deskflow-related)', (await until(() => h.calls.slice(n).some((c) => c[1] === 'link_import'))) && h.calls.slice(n).every((c) => !/deskflow/i.test(c[1])) && (await until(() => sw.eval(`/읽어 왔어요/.test(document.querySelector('.swin .toast')?.textContent ?? '')`))))
  // 페어링: 숫자가 하나씩 · 같아요 → link_pair(true)
  await sw.clickSel('.swin [data-ltab=devices]')
  await h.emit('link-files', { kind: 'peer', state: 'pairing', name: 'MacBook Pro', code: '482913' })
  ok('pairing request → 6 digits in the 기기 tab + badge on the tab', await until(() => sw.eval(`document.querySelector('.swin .pairpanel .code')?.dataset.code === '482913' && document.querySelectorAll('.swin .pairpanel .code span').length === 6 && !!document.querySelector('.swin [data-ltab=devices] .badge')`)))
  n = h.calls.length
  await sw.clickSel('.swin .pairpanel [data-pair=ok]')
  ok('같아요 → digits merge into "연결됨", then link_pair(ok: true)', (await until(() => sw.eval(`!!document.querySelector('.swin .pairpanel .mx-ok')`), 2000)) && (await until(() => h.calls.slice(n).some((c) => c[1] === 'link_pair' && c[2].ok === true), 3000)))
  await h.emit('link-files', { kind: 'peer', state: 'ready', name: 'MacBook Pro', code: '' })
  await h.emitTo('settings', 'settings-sec', 'link:layout')
  ok('settings-sec event (hub 연결 → 설정) switches section + tab', await until(() => sw.eval(`document.querySelector('.swin [data-ltab=layout]').classList.contains('on')`)))

  /* 채팅 · 터미널 · 단축키 · 정보 */
  await sw.clickSel('.swin .nav [data-sec=chat]')
  await until(async () => (await sec()) === 'chat')
  await sw.eval(`(() => { const s = ${row('이 PC 에 보관')}.querySelector('select'); s.value = '90'; s.dispatchEvent(new Event('change', { bubbles: true })) })()`)
  ok('채팅 보관 → chat.retentionDays = 90', await until(() => h.store.get('chat.retentionDays') === 90))
  ok('Team groups live under 채팅', await sw.eval(`!!document.querySelector('.swin .teamcard')`))
  await sw.clickSel('.swin .nav [data-sec=term]')
  await until(async () => (await sec()) === 'term')
  await press('마지막 명령도 넘기기')
  ok('아라 명령 넘기기 → term.araCmd', await until(() => h.store.get('term.araCmd') === true))
  ok('MCP lives under 터미널 · 아라', await sw.eval(`!!document.querySelector('.swin .mcpcard')`))
  await sw.clickSel('.swin .nav [data-sec=keys]')
  ok('단축키 shows the real hotkeys (Ctrl+Alt+K · Ctrl+`)', await until(() => sw.eval(`/CtrlAltK/.test(document.querySelector('.swin .pin').textContent.replace(/\\s/g, '')) && /Ctrl\`/.test(document.querySelector('.swin .pin').textContent.replace(/\\s/g, ''))`)))
  await sw.clickSel('.swin .nav [data-sec=about]')
  ok('정보 shows the version', await until(() => sw.eval(`/Hera/.test(document.querySelector('.swin .about').textContent)`)))
  const soon = await sw.eval(`[...document.querySelectorAll('.swin [data-soon]')].length`)
  ok('준비 중 rows are marked (here: 정보 · 업데이트 확인)', soon >= 1, String(soon))

  /* 아일랜드에서 열기 · Esc 로 닫기 */
  n = h.calls.length
  await sw.key('Escape')
  ok('Esc closes the settings window (close_self)', await until(() => !h.pages.has('settings')))
  const isl = await h.open('island')
  await until(() => isl.eval(`!!document.querySelector('.isl .pet')`), 8000)
  await sleep(400)
  await isl.clickSel('.isl .petbox')
  await until(() => isl.eval(`document.querySelector('.isl .skin').offsetWidth === 432`))
  await sleep(300)
  await isl.clickSel('.hub .app[data-go=settings]')
  ok('hub 설정 icon opens the settings window', await until(() => h.pages.has('settings') && h.calls.some((c) => c[1] === 'settings_open' && c[2].sec === 'general')))
  // 알림을 끈 채 날짜 없이 저장한 할 일 = 날짜 없음 (알림 없음)
  await h.closePage('settings')
  await isl.clickSel('.isl .petbox').catch(() => {})
  await until(() => isl.eval(`document.querySelector('.isl').dataset.open === 'true'`))
  await sleep(400)
  if (await isl.eval(`!!document.querySelector('.isl .view')`)) await isl.clickSel('.isl .view [data-back]')
  await sleep(400)
  await isl.clickSel('.hub .app[data-go=todo]')
  await isl.clickSel('.view[data-k=todo] .add input')
  await isl.type('조용한 할 일')
  await isl.key('Enter')
  ok('quick todo with the alarm off is saved without dates', await until(() => [...h.store.values()].some((v) => v?.title === '조용한 할 일' && !v.due && !v.start)))
  await isl.clickSel('.isl .view [data-back]')
  await until(() => isl.eval(`document.querySelector('.isl .skin').offsetWidth === 432 && !!document.querySelector('.hub .app[data-go=settings]')`))
  await sleep(300)
  await isl.clickSel('.hub .app[data-go=settings]')
  await until(() => h.pages.has('settings'))
  const sw2 = h.pages.get('settings')
  await until(() => sw2.eval(`!!document.querySelector('.swin .nav')`), 8000)
  ok('no page errors', sw.errors.length + sw2.errors.length + isl.errors.length === 0, [...sw.errors, ...sw2.errors, ...isl.errors].slice(0, 2).join(' | '))
} catch (e) {
  ok('suite ran to the end', false, String(e?.stack ?? e))
} finally {
  await h.close()
}
process.exit(done() ? 1 : 0)
